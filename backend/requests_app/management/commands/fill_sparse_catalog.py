class Command(BaseCommand):
    help = "Fill sparse catalog categories with 6 market-style products each"

    def handle(self, *args, **options):
        for spec in CATALOGS:
            category = self._category(spec)
            self._fill(category, spec["products"], spec["fallback_image"])
        self.stdout.write(self.style.SUCCESS("Sparse categories filled"))

    def _category(self, spec):
        names = spec.get("db_names") or [spec["name"]]
        category = Category.objects.filter(name__in=names).first()
        if category is None:
            category = Category.objects.create(
                name=spec["name"],
                description=spec["name"],
                is_active=True,
            )
        elif category.name != spec["name"]:
            category.name = spec["name"]
        category.is_active = True
        category.save()
        return category

    def _fill(self, category, products, fallback_image):
        existing = list(Product.objects.filter(category=category).order_by("id"))
        used_ids = set()
        for index, (name, height, width, depth, description) in enumerate(products):
            product = Product.objects.filter(category=category, name=name).first()
            if product is None and index < len(existing) and existing[index].id not in used_ids:
                product = existing[index]
            if product is None:
                product = Product(category=category, name=name)
            product.name = name
            product.description = description
            product.height = height
            product.width = width
            product.depth = depth
            product.category = category
            product.is_active = True
            product.save()
            used_ids.add(product.id)
            if not product.image:
                self._attach_image(product, existing, fallback_image)
            self.stdout.write(f"{category.name}: {product.name} ({product.height}x{product.width}x{product.depth})")

        Product.objects.filter(category=category).exclude(id__in=used_ids).update(is_active=False)

    def _attach_image(self, product, existing, fallback_image):
        for donor in existing:
            if donor.image and donor.image.name:
                try:
                    path = Path(donor.image.path)
                except Exception:
                    path = None
                if path and path.is_file():
                    with path.open("rb") as fh:
                        product.image.save(path.name, File(fh), save=True)
                    return
        if fallback_image.is_file():
            with fallback_image.open("rb") as fh:
                product.image.save(fallback_image.name, File(fh), save=True)
