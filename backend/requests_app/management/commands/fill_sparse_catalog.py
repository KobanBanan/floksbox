class Command(BaseCommand):
    help = "Поставить рекомендованные товары в разделы, кроме четырёхклапанных коробок, пакетов и шляпных коробок"

    def handle(self, *args, **options):
        for spec in CATALOGS:
            for item in spec["products"]:
                words = len(item[5].split())
                if words > 200:
                    raise SystemExit(f"{item[0]}: {words} слов")
                if item[4]:
                    image = SEED / item[4]
                    if not image.is_file():
                        raise SystemExit(f"Нет файла {image}")
            category = self._category(spec["name"])
            self._fill(category, spec["products"])
        self.stdout.write(self.style.SUCCESS("Рекомендованные товары записаны"))

    def _category(self, name):
        category = Category.objects.filter(name=name).first()
        if category is None:
            category = Category.objects.create(name=name, description=name, is_active=True)
        category.is_active = True
        category.save()
        return category

    def _fill(self, category, products):
        existing = list(Product.objects.filter(category=category).order_by("id"))
        used_ids = set()
        now = timezone.now()
        for index, (name, height, width, depth, image_name, description) in enumerate(products):
            product = Product.objects.filter(category=category, name=name).first()
            if product is None and index < len(existing) and existing[index].id not in used_ids:
                product = existing[index]
            if product is None:
                product = Product(category=category, name=name)
            product.name = name
            product.description = description
            product.height = height
            product.width = width
            product.depth = depth
            product.price = None
            product.category = category
            product.is_active = True
            product.image_unfold = None
            product.created_at = now - timedelta(minutes=index)
            product.save()
            used_ids.add(product.id)
            if image_name:
                image_path = SEED / image_name
                with image_path.open("rb") as fh:
                    product.image.save(image_name, File(fh), save=True)
            else:
                if product.image:
                    product.image.delete(save=False)
                product.image = None
                product.save(update_fields=["image"])
            self.stdout.write(f"{category.name}: {product.name}")

        Product.objects.filter(category=category).exclude(id__in=used_ids).update(is_active=False)
