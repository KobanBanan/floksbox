class Command(BaseCommand):
    help = "Replace four-flap category products with quadpack catalog items"

    def handle(self, *args, **options):
        if not DATA_DIR.is_dir():
            self.stderr.write(f"Images directory not found: {DATA_DIR}")
            return

        category, _ = Category.objects.get_or_create(
            name=CATEGORY_NAME,
            defaults={
                "description": "Четырехклапанные гофрокороба стандартных и индивидуальных размеров.",
                "is_active": True,
            },
        )
        category.is_active = True
        category.save()

        deleted_count, _ = Product.objects.filter(category=category).delete()
        self.stdout.write(f"Deleted {deleted_count} old products in category")

        created = 0
        for item in sorted(PRODUCTS, key=lambda p: p["sort"], reverse=True):
            image_path = DATA_DIR / item["image"]
            if not image_path.is_file():
                self.stderr.write(f"Missing image: {image_path}")
                continue

            product = Product(
                name=item["name"],
                description=item["description"],
                category=category,
                height=30,
                width=20,
                depth=15,
                is_active=True,
            )
            product.save()

            with image_path.open("rb") as image_file:
                product.image.save(image_path.name, File(image_file), save=True)

            created += 1
            self.stdout.write(f"Created: {product.name} (id={product.id})")

        self.stdout.write(self.style.SUCCESS(f"Done: created={created}, category={category.name}"))
